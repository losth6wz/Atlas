/* USER CODE END Header_StartAtlasTask */
void StartAtlasTask(void *argument)
{
  /* USER CODE BEGIN 5 */
	char gps_line[128];
  /* Infinite loop */
  for(;;)
  {
	  Atlas_Update();
	  uint8_t gps_byte;
	  char gps_debug[32];

	  if (HAL_UART_Receive(
	          &huart1,
	          &gps_byte,
	          1,
	          200
	      ) == HAL_OK)
	  {
	      snprintf(
	          gps_debug,
	          sizeof(gps_debug),
	          "GPS BYTE: 0x%02X '%c'\r\n",
	          gps_byte,
	          (gps_byte >= 32 && gps_byte <= 126)
	              ? gps_byte
	              : '.'
	      );

	      Telemetry_SendText(gps_debug);
	  }

	  osDelay(100);
  }
  /* USER CODE END 5 */
}

